var import_obsidian15 = require("obsidian");
var MentionHelper = class {
  /**
   * Returns all searchable files and folders in the Vault for @ autocomplete suggestions.
   */
  static getVaultItems(app, query = "") {
    const allFiles = app.vault.getAllLoadedFiles();
    const queryLower = query.toLowerCase();
    const items = [];
    for (const item of allFiles) {
      if (item.path === "/" || item.path === "")
        continue;
      const isFolder = item instanceof import_obsidian15.TFolder;
      if (!queryLower || item.name.toLowerCase().includes(queryLower) || item.path.toLowerCase().includes(queryLower)) {
        items.push({
          name: item.name,
          path: item.path,
          isFolder
        });
      }
    }
    return items.sort((a, b) => {
      if (a.isFolder && !b.isFolder)
        return -1;
      if (!a.isFolder && b.isFolder)
        return 1;
      return a.path.localeCompare(b.path);
    }).slice(0, 15);
  }
  /**
   * Scans a message for @references and attaches the real file/folder contents.
   */
  static async resolveMentions(app, userText) {
    const mentionRegex = /@([a-zA-Z0-9_\-\.\/]+)/g;
    const matches = Array.from(userText.matchAll(mentionRegex));
    if (matches.length === 0)
      return userText;
    let enrichedText = userText;
    const attachedBlocks = [];
    for (const match of matches) {
      const targetPath = match[1];
      const item = app.vault.getAbstractFileByPath(targetPath);
      if (item instanceof import_obsidian15.TFile) {
        try {
          const content = await app.vault.read(item);
          attachedBlocks.push(
            `[Attached Note: @${item.path}]
\`\`\`markdown
${content}
\`\`\``
          );
        } catch (e) {
        }
      } else if (item instanceof import_obsidian15.TFolder) {
        try {
          const children = item.children.map((c) => `- ${c.name} (${c instanceof import_obsidian15.TFolder ? "folder" : "file"})`).join("\n");
          attachedBlocks.push(
            `[Attached Folder: @${item.path}]
\`\`\`
${children}
\`\`\``
          );
        } catch (e) {
        }
      }
    }
    if (attachedBlocks.length > 0) {
      enrichedText = `${enrichedText}

${attachedBlocks.join("\n\n")}`;
    }
    return enrichedText;
  }
};

// src/utils/thought-helper.ts
function parseThoughts(raw) {
  if (!raw) {
    return { thoughts: [], finalAnswer: "" };
  }
  const thoughts = [];
  let clean = raw.replace(/<(?:thought|think)>([\s\S]*?)<\/(?:thought|think)>/gi, (_, thoughtContent) => {
    const trimmed = thoughtContent.trim();
    if (trimmed) {
      thoughts.push(trimmed);
    }
    return "";
  });
  const openMatch = clean.match(/<(?:thought|think)>([\s\S]*)$/i);
  if (openMatch) {
    const trimmed = openMatch[1].trim();
    if (trimmed) {
      thoughts.push(trimmed);
    }
    clean = clean.slice(0, openMatch.index);
  }
  return {
    thoughts,
    finalAnswer: clean.trim()
  };
}

