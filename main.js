function sortToolSchemasDeterministically(tools) {
  return [...tools].sort((a, b) => a.name.localeCompare(b.name)).map((tool) => {
    const properties = tool.parameters.properties;
    const sortedPropertyKeys = Object.keys(properties).sort();
    const sortedProperties = {};
    for (const key of sortedPropertyKeys) {
      sortedProperties[key] = properties[key];
    }
    return {
      ...tool,
      parameters: {
        ...tool.parameters,
        properties: sortedProperties,
        required: tool.parameters.required ? [...tool.parameters.required].sort() : void 0
      }
    };
  });
}
function prepareNetworkPayloadMessages(messages) {
  if (messages.length === 0)
    return [];
  const networkMessages = JSON.parse(JSON.stringify(messages));
  for (let i = networkMessages.length - 1; i >= 0; i--) {
    if (networkMessages[i].role === "user" && typeof networkMessages[i].content === "string") {
      const nowIso = (/* @__PURE__ */ new Date()).toISOString();
      networkMessages[i].content = `${networkMessages[i].content}

[Current Date & Time: ${nowIso}]`;
      break;
    }
  }
  return networkMessages;
}

// src/engine/stream-parser.ts
var SSEStreamParser = class {
  constructor() {
    this.buffer = "";
  }
  /**
   * Processes a chunk of string text and extracts completed SSE event lines.
   */
  feed(chunk) {
    this.buffer += chunk;
    const events = [];
    const lines = this.buffer.split("\n");
    this.buffer = lines.pop() || "";
    let currentEvent = {};
    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed) {
        if (currentEvent.data !== void 0) {
          events.push(currentEvent);
          currentEvent = {};
        }
        continue;
      }
      if (trimmed.startsWith("event:")) {
        currentEvent.event = trimmed.substring(6).trim();
      } else if (trimmed.startsWith("data:")) {
        const dataPart = trimmed.substring(5).trim();
        if (currentEvent.data) {
          currentEvent.data += "\n" + dataPart;
        } else {
          currentEvent.data = dataPart;
        }
      }
    }
    return events;
  }
};

